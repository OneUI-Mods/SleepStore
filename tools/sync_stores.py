"""Generate recommendation metadata; the hook itself accepts any framework-selected app."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
entries=json.loads((root/'config/stores.json').read_text())
packages=list(dict.fromkeys(p for e in entries for p in e['packages']))
p=root/'app/src/main/AndroidManifest.xml'
s=p.read_text();start=s.index('    <queries>');end=s.index('</queries>',start)+len('</queries>')
s=s[:start]+'    <queries>\n'+''.join('        <package android:name="'+p+'"/>\n' for p in packages)+'    </queries>'+s[end:];p.write_text(s)
(root/'app/src/main/resources/META-INF/xposed/scope.list').write_text(
    '\n'.join(packages+['dev.ryuya.sleepstore'])+'\n')
arrays=',\n        '.join('{'+','.join(json.dumps(p) for p in e['packages'])+'}' for e in entries)
labels=','.join('R.string.'+e['label'] for e in entries)
(root/'app/src/main/java/dev/ryuya/sleepstore/Targets.java').write_text('''package dev.ryuya.sleepstore;

// Generated by tools/sync_stores.py from config/stores.json. Not a hook allowlist.
final class Targets {
    static final String[][] PACKAGES={
        '''+arrays+'''
    };
    static final int[] LABELS={'''+labels+'''};
    static String installedPackage(android.content.Context context,int index) {
        for(String pkg:PACKAGES[index]) {
            try {context.getPackageManager().getPackageInfo(pkg,0);return pkg;}
            catch(android.content.pm.PackageManager.NameNotFoundException ignored) { }
        }
        return null;
    }
    private Targets() {}
}
''')
